export function localizeUnit(unit, lang) {
  if (lang === 'uz' || !unit) return unit
  let value = unit
  if (lang === 'ru') {
    value = value.replace(/\bkg\b/g, 'кг').replace(/\bgr\b/g, 'г').replace(/\bL\b/g, 'л')
    value = value.replace(/dona/g, 'шт').replace(/paket/g, 'пачек')
  } else {
    value = value.replace(/\bkg\b/g, 'kg').replace(/\bgr\b/g, 'g').replace(/\bL\b/g, 'L')
    value = value.replace(/dona/g, 'pc').replace(/paket/g, 'packs')
    value = value.replace(/,/g, '.')
  }
  return value
}

/** Mahsulotni tanlangan tilga moslashtiradi. */
export function localizeProduct(product, lang) {
  if (!product || lang === 'uz') return product
  const tr = PRODUCT_I18N[product.id]?.[lang]
  return {
    ...product,
    name: tr?.name || product.name,
    description: tr?.description || product.description,
    unit: localizeUnit(product.unit, lang),
  }
}

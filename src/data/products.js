const byId = Object.fromEntries(SEED_PRODUCTS.map((p) => [p.id, p]))
const snap = (id, qty) => {
  const p = byId[id]
  return { id, name: p.name, price: p.price, qty, unit: p.unit, image: p.image }
}
const hoursAgo = (h) => new Date(Date.now() - h * 60 * 60 * 1000).toISOString()

const demoOrder = ({ id, status, payment, hours, customer, items }) => {
  const orderItems = items.map(([pid, qty]) => snap(pid, qty))
  const subtotal = orderItems.reduce((sum, i) => sum + i.price * i.qty, 0)
  const delivery = subtotal >= FREE_DELIVERY_THRESHOLD ? 0 : DELIVERY_FEE
  return {
    id,
    customer,
    items: orderItems,
    subtotal,
    delivery,
    total: subtotal + delivery,
    payment,
    status,
    createdAt: hoursAgo(hours),
  }
}

